"""Storage and external-service contracts used by application services."""

from contextlib import AbstractAsyncContextManager
from typing import Protocol

from .domain import Order, RemotePayment, Subscription


class Transaction(Protocol):
    async def order(self, order_id: str) -> Order | None: ...
    async def by_request(self, request_key: str) -> Order | None: ...
    async def add_order(self, order: Order) -> None: ...
    async def save_order(self, order: Order) -> None: ...
    async def subscription(self, telegram_id: int) -> Subscription | None: ...
    async def save_subscription(self, subscription: Subscription) -> None: ...


class Store(Protocol):
    def transaction(self, telegram_id: int) -> AbstractAsyncContextManager[Transaction]: ...
    async def order(self, order_id: str) -> Order | None: ...
    async def by_payment(self, payment_id: str) -> Order | None: ...
    async def subscription(self, telegram_id: int) -> Subscription | None: ...
    async def by_short_id(self, short_id: str) -> Subscription | None: ...
    async def pending_orders(self) -> list[Order]: ...
    async def unsynced(self) -> list[Subscription]: ...
    async def pending_notifications(self) -> list[Order]: ...


class PaymentGateway(Protocol):
    async def create(self, order: Order) -> RemotePayment: ...
    async def fetch(self, payment_id: str) -> RemotePayment: ...


class Panel(Protocol):
    async def ensure(self, subscription: Subscription) -> int: ...
